/** The list the picker shows and the search runs over. */
export const EMOJI = RAW.map(([ch, en]) => ({ ch, en, pl: EMOJI_NAMES_PL[ch] || "" }));

/** Strip diacritics and lowercase: a capitalised or accented query matches the plain name. */
export function foldName(s) {
  return String(s ?? "").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/ł/g, "l").toLowerCase();
}

export function recentEmoji() {
  try {
    const list = JSON.parse(localStorage.getItem(RECENT_KEY) || "[]");
    return Array.isArray(list) ? list.filter((x) => typeof x === "string").slice(0, RECENT_MAX) : [];
  } catch { return []; }
}

export function rememberEmoji(ch) {
  const next = [ch, ...recentEmoji().filter((x) => x !== ch)].slice(0, RECENT_MAX);
  try { localStorage.setItem(RECENT_KEY, JSON.stringify(next)); } catch { /* private browsing */ }
  return next;
}

/**
 * Search by name. An empty query lists the recently used first, then the whole list in order.
 * A match on a word start ranks before a match inside a word; English and Polish names are
 * both searched whatever the UI language, the UI language only decides which wins a tie.
 * @param {string} query
 * @param {"en"|"pl"} [lang]
 * @returns {Emoji[]}
 */
export function searchEmoji(query, lang = "en") {
  const q = foldName(query).trim();
  if (!q) {
    const recent = recentEmoji();
    const byCh = new Map(EMOJI.map((e) => [e.ch, e]));
    const first = recent.map((ch) => byCh.get(ch) ?? { ch, en: "", pl: "" });
    return [...first, ...EMOJI.filter((e) => !recent.includes(e.ch))];
  }
  const scored = [];
  for (const e of EMOJI) {
    const names = lang === "pl" ? [e.pl, e.en] : [e.en, e.pl];
    let best = 0;
    names.forEach((n, i) => {
      const words = foldName(n).split(" ");
      if (words.some((w) => w.startsWith(q))) best = Math.max(best, 3 - i);
      else if (words.some((w) => w.includes(q))) best = Math.max(best, 1);
    });
    if (best) scored.push({ e, best });
  }
  scored.sort((a, b) => b.best - a.best);
  return scored.map((s) => s.e);
}
